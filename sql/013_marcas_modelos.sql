-- Marcas y modelos de vehículos para el labrado (dropdowns administrables desde Configuración).
CREATE TABLE IF NOT EXISTS vehiculo_marca (
  id BIGSERIAL PRIMARY KEY, nombre VARCHAR(80) NOT NULL UNIQUE, activa BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS vehiculo_modelo (
  id BIGSERIAL PRIMARY KEY, marca_id BIGINT NOT NULL REFERENCES vehiculo_marca(id) ON DELETE CASCADE,
  nombre VARCHAR(80) NOT NULL, tipo_vehiculo VARCHAR(40), activa BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (marca_id, nombre)
);

