export const PARTIDOS = Object.keys(DATOS).sort((a, b) => (a === CABA ? -1 : b === CABA ? 1 : a.localeCompare(b, 'es')));

/** Localidades únicas (una entrada por nombre) con los partidos donde existen. */
export const LOCALIDADES: { nombre: string; partidos: string[] }[] = (() => {
  const m = new Map<string, Set<string>>();
  for (const [p, locs] of Object.entries(DATOS)) for (const l of locs) (m.get(l) ?? m.set(l, new Set()).get(l)!).add(p);
  return [...m].map(([nombre, s]) => ({ nombre, partidos: [...s].sort() })).sort((a, b) => a.nombre.localeCompare(b.nombre, 'es'));
})();

export function partidosDe(localidad: string): string[] {
  return LOCALIDADES.find((l) => l.nombre === localidad)?.partidos ?? [];
}
